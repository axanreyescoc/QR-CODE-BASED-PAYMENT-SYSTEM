    private void qrbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_qrbtnActionPerformed
        // TODO add your handling code here:

        String id = TxtID.getText().trim();
        String name = txtName.getText().trim();
        String course = txtDepartment.getText().trim();
        String contact = txtnum.getText().trim();
        String payment = boxpay.getSelectedItem().toString();
        String amount = txtamount.getText().trim();
        String email = txtemail.getText().trim();

        // Kung "Other, pls specify" ang pinili, kunin ang value mula sa txtOther
        if (payment.equals("Other, pls specify")) {
            String specifiedPayment = txtOther.getText().trim();
            
            // I-check kung blangko ang txtOther
            if (specifiedPayment.isEmpty()) {
                JOptionPane.showMessageDialog(
                    this,
                    "Please specify the payment type.",
                    "Incomplete Information",
                    JOptionPane.WARNING_MESSAGE
                );
                return;
            }
            
            // Palitan ang payment value ng inilagay ng user sa txtOther
            payment = specifiedPayment;
        }

        // Check kung may blangkong kinakailangang field
        if (id.isEmpty() || name.isEmpty() || course.isEmpty() || contact.isEmpty() || amount.isEmpty()|| email.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Please complete all fields.",
                "Incomplete Information",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        // Isalin ang tamang payment value sa finance window
        finance d = new finance(
            id,
            name,
            course,
            contact,
            payment,
            amount,
                email
        );

        d.setVisible(true);
        this.dispose();
    }//GEN-LAST:event_qrbtnActionPerformed

