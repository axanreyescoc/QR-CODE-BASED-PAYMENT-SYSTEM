private void displayQrImage(BufferedImage image) {
    currentQrImage = image;

    Image scaledImage = image.getScaledInstance(
        250,
        250,
        Image.SCALE_SMOOTH
    );

    qr1.setIcon(new ImageIcon(scaledImage));
    qr1.setText("");
    qr1.setHorizontalAlignment(
        javax.swing.SwingConstants.CENTER
    );
    qr1.setVerticalAlignment(
        javax.swing.SwingConstants.CENTER
    );
}

private void resizeQrImage() {
    if (currentQrImage == null) {
        return;
    }

    int width = qr1.getWidth();
    int height = qr1.getHeight();

    if (width <= 0 || height <= 0) {
        return;
    }

    double scale = Math.min(
        (double) width / currentQrImage.getWidth(),
        (double) height / currentQrImage.getHeight()
    );

    int newWidth = Math.max(
        1, (int) (currentQrImage.getWidth() * scale)
    );

    int newHeight = Math.max(
        1, (int) (currentQrImage.getHeight() * scale)
    );

    Image scaledImage = currentQrImage.getScaledInstance(
        newWidth,
        newHeight,
        Image.SCALE_SMOOTH
    );

    qr1.setHorizontalAlignment(
        javax.swing.SwingConstants.CENTER
    );

    qr1.setVerticalAlignment(
        javax.swing.SwingConstants.CENTER
    );

    qr1.setIcon(new ImageIcon(scaledImage));
    qr1.setText("");
}
    
