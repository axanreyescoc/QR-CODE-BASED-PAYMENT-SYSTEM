    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        
         PrinterJob job = PrinterJob.getPrinterJob();

    // Set the receipt content to be printed
    job.setPrintable((graphics, pageFormat, pageIndex) -> {

        if (pageIndex > 0) {
            return java.awt.print.Printable.NO_SUCH_PAGE;
        }

        java.awt.Graphics2D g2 =
                (java.awt.Graphics2D) graphics;

        g2.translate(
                pageFormat.getImageableX(),
                pageFormat.getImageableY()
        );

        // Scale receipt to fit the printable page
        double scaleX =
                pageFormat.getImageableWidth() / getWidth();

        double scaleY =
                pageFormat.getImageableHeight() / getHeight();

        double scale = Math.min(scaleX, scaleY);

        g2.scale(scale, scale);

        // Print the receipt without the Print button
        jButton1.setVisible(false);
        printAll(g2);
        jButton1.setVisible(true);

        return java.awt.print.Printable.PAGE_EXISTS;
    });

    if (job.printDialog()) {
        try {
            job.print();

            JOptionPane.showMessageDialog(
                    this,
                    "Receipt printed successfully!"
            );

        } catch (PrinterException ex) {
            JOptionPane.showMessageDialog(
                    this,
                    "Failed to print receipt:\n" + ex.getMessage(),
                    "Print Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }
    }//GEN-LAST:event_jButton1ActionPerformed

