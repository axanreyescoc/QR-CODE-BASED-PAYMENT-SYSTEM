    private void bloginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bloginActionPerformed
        // TODO add your handling code here:
        
   String id = jtuser.getText().trim();
String password = new String(jpassword.getPassword());

AccountStore.Account account =
        AccountStore.login(id, password);

if (account == null) {
    JOptionPane.showMessageDialog(
        this,
        "Invalid ID or Password",
        "Login Error",
        JOptionPane.ERROR_MESSAGE
    );
    return;
}

if (account.role.equals("STUDENT")) {
    Menu studentMenu = new Menu(
        account.id,
        account.name,
        account.department,
        account.email == null ? "" : account.email
    );
    studentMenu.setVisible(true);
    this.dispose();

} else if (account.role.equals("CASHIER")) {
    Cashier cashierFrame = new Cashier();
    cashierFrame.setVisible(true);
    this.dispose();

} else if (account.role.equals("ADMIN")) {
    admin adminFrame = new admin();
    adminFrame.setVisible(true);
    this.dispose();

} else {
    JOptionPane.showMessageDialog(this, "Unknown account type.");
}
    }//GEN-LAST:event_bloginActionPerformed

